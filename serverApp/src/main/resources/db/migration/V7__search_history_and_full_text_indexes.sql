CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS search_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    query text NOT NULL,
    search_type varchar(30) NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT search_history_pk PRIMARY KEY (id),
    CONSTRAINT search_history_user_fk FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE INDEX IF NOT EXISTS idx_search_history_user_created ON search_history (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_search_history_query_lower ON search_history (LOWER(query));

CREATE INDEX IF NOT EXISTS idx_event_search_tsv ON event USING GIN (
    to_tsvector('simple', COALESCE(name, '') || ' ' || COALESCE(description, ''))
);
CREATE INDEX IF NOT EXISTS idx_event_name_trgm ON event USING GIN (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_location_name_trgm ON location USING GIN (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_app_user_username_trgm ON app_user USING GIN (username gin_trgm_ops);
